#requires -Version 5.1
<#
.SYNOPSIS
  Install per-project rules into each project's own repo (.claude/), git-excluded.
.DESCRIPTION
  Separate from install.ps1 on purpose: it writes into your PROJECT repos, so you
  run it deliberately (and never while a session on that repo is mid-task). For
  each projects/<name>.md whose `repo:` path exists, it:
    - copies the project rule to <repo>/.claude/rules/harness-<name>.md
    - copies the named stacks to <repo>/.claude/rules/harness/stacks/...
    - generates <repo>/.claude/CLAUDE.md that @imports them (relative paths)
    - adds `.claude/` to <repo>/.git/info/exclude (never committed)
  It refuses to overwrite a <repo>/.claude/CLAUDE.md it did not generate.
.PARAMETER Only
  Restrict to one project name (e.g. -Only my-app).
.PARAMETER DryRun
  Show what would happen; write nothing.
.EXAMPLE
  .\install-projects.ps1 -DryRun
  .\install-projects.ps1 -Only my-app
#>
[CmdletBinding()]
param([string]$Only = '', [switch]$DryRun)
$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$Marker   = '<!-- claude-harness:project -->'
function Say([string]$m,[string]$c='Gray'){ Write-Host $m -ForegroundColor $c }
function Read-Utf8([string]$p){ [IO.File]::ReadAllText($p,[Text.Encoding]::UTF8) }
function Write-Utf8([string]$p,[string]$s){
  if($DryRun){ Say "  would write: $p" 'DarkYellow'; return }
  $d=Split-Path $p; if(-not(Test-Path $d)){ New-Item -ItemType Directory -Force $d|Out-Null }
  [IO.File]::WriteAllText($p,$s,(New-Object Text.UTF8Encoding($false))); Say "  wrote: $p" 'DarkGreen'
}

Say "claude-harness project installer" 'Cyan'
if($DryRun){ Say "  DRY RUN" 'Yellow' }

Get-ChildItem (Join-Path $RepoRoot 'projects') -Filter '*.md' -File | ForEach-Object {
  $name = [IO.Path]::GetFileNameWithoutExtension($_.Name)
  if($Only -and $name -ne $Only){ return }
  $text = Read-Utf8 $_.FullName
  # parse frontmatter: repo + stacks
  $repo = ''; $stacks = @()
  if($text -match '(?s)^---\s*(.*?)\s*---'){
    $fm = $Matches[1]
    if($fm -match 'repo:\s*(.+)'){ $repo = $Matches[1].Trim() }
    if($fm -match 'stacks:\s*\[(.*?)\]'){ $stacks = ($Matches[1] -split ',') | ForEach-Object { $_.Trim() } | Where-Object { $_ } }
  }
  Say "`n[$name] repo=$repo stacks=$($stacks -join ',')" 'Cyan'
  if(-not $repo){ Say "  no repo: (e.g. a-pine-strategy) - skill/vault-based, nothing to install" 'DarkGray'; return }
  if(-not (Test-Path $repo)){ Say "  repo path not found; skipping" 'Yellow'; return }

  $claudeDir = Join-Path $repo '.claude'
  $repoCM    = Join-Path $claudeDir 'CLAUDE.md'
  if((Test-Path $repoCM) -and ((Read-Utf8 $repoCM) -notmatch [regex]::Escape($Marker))){
    Say "  SKIP: $repoCM exists and is not harness-generated (won't overwrite)" 'Yellow'; return
  }

  # 1. project rule (tokens already substituted at author time; copy as-is)
  Write-Utf8 (Join-Path $claudeDir "rules\harness-$name.md") $text
  $imports = @("@rules/harness-$name.md")
  # 2. named stacks, copied local for relative import
  foreach($st in $stacks){
    $src = Join-Path $RepoRoot "rules\stacks\$st\$st.md"
    if(Test-Path $src){
      Write-Utf8 (Join-Path $claudeDir "rules\harness\stacks\$st\$st.md") (Read-Utf8 $src)
      $imports += "@rules/harness/stacks/$st/$st.md"
    } else { Say "  stack '$st' not found in harness; skipped" 'Yellow' }
  }
  # 3. repo CLAUDE.md that imports them
  $cm = "# Project rules (managed by claude-harness) $Marker`n`n" +
        "> Generated by install-projects.ps1. Edit the harness repo, not this file.`n`n" +
        (($imports | ForEach-Object { $_ }) -join "`n") + "`n"
  Write-Utf8 $repoCM $cm
  # 4. git-exclude .claude/
  $excl = Join-Path $repo '.git\info\exclude'
  if(Test-Path (Split-Path $excl)){
    $cur = ''; if(Test-Path $excl){ $cur = Read-Utf8 $excl }
    if($cur -notmatch '(?m)^\.claude/?$'){
      if($DryRun){ Say "  would git-exclude .claude/" 'DarkYellow' }
      else { Add-Content -Path $excl -Value ".claude/" -Encoding UTF8; Say "  git-excluded .claude/" 'DarkGreen' }
    }
  }
}
Say "`nDone." 'Green'
